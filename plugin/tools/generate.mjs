// Writes the generated C++ the plugin needs, so the build itself needs neither
// Node.js nor the Faust compiler. The output is committed.
//
//   node plugin/tools/generate.mjs           parameters only (needs Node.js)
//   node plugin/tools/generate.mjs --dsp     also the Faust C++ (needs `faust` on PATH,
//                                            or FAUST=/path/to/faust, and `npm install` in dsp/)
//   node plugin/tools/generate.mjs --check   fail if a committed file is out of date (for CI)
//
// Presets: the 100 factory sounds from presets.js, for Live's preset menu.
//
// Parameters: every panel control that shapes the sound becomes a DAW parameter.
// Its ID is the control id from panel.js. IDs must never change after the
// first release, or saved Live sets lose their settings.
//
// Faust C++: compiled from dsp/halden6.dsp with the Faust libraries bundled in
// @grame/faustwasm, the same library code the web version is built with.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..', '..');
const outDir = path.join(here, '..', 'Source', 'generated');
const args = process.argv.slice(2);
const check = args.includes('--check');
const withDsp = args.includes('--dsp') || (check && args.includes('--dsp'));

let stale = [];
function emit(name, text) {
  const file = path.join(outDir, name);
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old === text) return;
  if (check) { stale.push(name); return; }
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(file, text);
  console.log('wrote', path.relative(root, file));
}

// ---------- parameters from panel.js ----------
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'panel.js'), 'utf8'), sandbox);
vm.runInNewContext(fs.readFileSync(path.join(root, 'presets.js'), 'utf8'), sandbox);
const PANEL = sandbox.window.PANEL;
const PRESETS = sandbox.window.PRESETS;

// Controls that are not DAW parameters: actions (panic), the pitch wheel (comes
// from MIDI pitch bend), and the arpeggiator with its tempo (phase 4).
const SKIP_TYPES = new Set(['button', 'wheel', 'tempo']);
const SKIP_ROWS = new Set(['arp1', 'arp2']);
// Sections whose title adds nothing to the parameter name in Live's list
const NO_PREFIX = new Set(['control', 'perf']);

const cstr = s => '"' + Buffer.from(s, 'utf8').toString('latin1').replace(/[\\"]/g, '\\$&')
  .replace(/[^\x20-\x7e]/g, ch => '\\x' + ch.charCodeAt(0).toString(16).padStart(2, '0') + '""') + '"';
const num = x => (Number.isInteger(x) ? x.toFixed(1) : String(x)) + 'f';

const params = [];
for (const s of PANEL) {
  if (SKIP_ROWS.has(s.row)) continue;
  for (const c of s.controls) {
    if (SKIP_TYPES.has(c.type)) continue;
    const name = NO_PREFIX.has(s.id) ? c.label : `${s.title} ${c.label}`;
    let type, min = 0, max = 1, options = [];
    if (c.type === 'slider' || c.type === 'knob') { type = 'Float'; min = c.bipolar ? -1 : 0; }
    else if (c.type === 'toggle') type = 'Bool';
    else if (c.type === 'switch' || c.type === 'select') { type = 'Choice'; options = c.options; max = options.length - 1; }
    else if (c.type === 'stepper') { type = 'Int'; min = c.min; max = c.max; }
    else throw new Error(`panel.js: control type "${c.type}" (${c.id}) has no parameter mapping`);
    params.push({ id: c.id, name, type, min, max, def: c.value ?? 0, options });
  }
}

let h = `// Generated by plugin/tools/generate.mjs from panel.js. Do not edit by hand.
#pragma once

namespace halden6
{
enum class ParamType { Float, Bool, Choice, Int };

struct ParamInfo
{
    const char* id;          // never change after the first release
    const char* name;        // shown in the DAW's automation list
    ParamType type;
    float min, max, def;     // Choice: index range; Bool: 0..1
    const char* const* options;
    int numOptions;
};

enum Param
{
${params.map(p => `    P_${p.id},`).join('\n')}
    kNumParams
};

`;
params.filter(p => p.options.length).forEach(p => {
  h += `inline const char* const options_${p.id}[] = { ${p.options.map(cstr).join(', ')} };\n`;
});
h += `
inline const ParamInfo kParams[kNumParams] = {
${params.map(p => `    { "${p.id}", ${cstr(p.name)}, ParamType::${p.type}, ${num(p.min)}, ${num(p.max)}, ${num(p.def)}, ${p.options.length ? 'options_' + p.id : 'nullptr'}, ${p.options.length} },`).join('\n')}
};
} // namespace halden6
`;
emit('Parameters.h', h);

// ---------- presets from presets.js ----------
const paramIds = new Set(params.map(p => p.id));
let ph = `// Generated by plugin/tools/generate.mjs from presets.js. Do not edit by hand.
#pragma once

#include "Parameters.h"

namespace halden6
{
struct PresetValue { int param; float value; };

struct Preset
{
    int num;
    const char* name;
    const char* category;
    const PresetValue* values;
    int numValues;
};

`;
PRESETS.forEach(p => {
  const vals = Object.entries(p.values).map(([id, v]) => {
    if (!paramIds.has(id)) throw new Error(`presets.js: "${p.name}" sets ${id}, which is not a plugin parameter`);
    return `{ P_${id}, ${num(+v.toFixed(6))} }`;
  });
  ph += `inline const PresetValue preset${p.num}[] = { ${vals.join(', ')} };\n`;
});
ph += `
inline const Preset kPresets[] = {
${PRESETS.map(p => `    { ${p.num}, ${cstr(p.name)}, ${cstr(p.cat)}, preset${p.num}, ${Object.keys(p.values).length} },`).join('\n')}
};
constexpr int kNumPresets = ${PRESETS.length};
} // namespace halden6
`;
emit('Presets.h', ph);

// ---------- Faust C++ from halden6.dsp ----------
if (withDsp) {
  const faust = process.env.FAUST || 'faust';
  const fw = path.join(root, 'dsp', 'node_modules', '@grame', 'faustwasm');
  if (!fs.existsSync(fw)) throw new Error('run `npm install` in dsp/ first (it provides the Faust libraries)');
  const { instantiateFaustModuleFromFile, LibFaust, FaustCompiler } = await import(path.join(fw, 'dist', 'esm', 'index.js'));
  const lib = new FaustCompiler(new LibFaust(await instantiateFaustModuleFromFile(path.join(fw, 'libfaust-wasm', 'libfaust-wasm.js'))));
  const libDir = fs.mkdtempSync(path.join(os.tmpdir(), 'halden6-faustlibs-'));
  for (const f of lib.fs().readdir('/usr/share/faust')) {
    if (f.endsWith('.lib')) fs.writeFileSync(path.join(libDir, f), lib.fs().readFile('/usr/share/faust/' + f, { encoding: 'utf8' }));
  }
  const dsp = path.join(root, 'dsp', 'halden6.dsp');
  for (const [cn, extra] of [['Halden6Voice', []], ['Halden6Effect', ['-pn', 'effect']]]) {
    const tmp = path.join(libDir, cn + '.h');
    execFileSync(faust, ['-lang', 'cpp', '-cn', cn, ...extra, '-I', libDir, '-A', libDir, dsp, '-o', tmp]);
    // The header lists the compiler's own command line; drop the temp path from it
    const text = '// Generated by plugin/tools/generate.mjs from dsp/halden6.dsp. Do not edit by hand.\n' +
      fs.readFileSync(tmp, 'utf8').replaceAll(libDir, '<faustwasm libraries>');
    emit(cn + '.h', text);
  }
  fs.rmSync(libDir, { recursive: true, force: true });
}

if (check && stale.length) {
  console.error('Out of date, run plugin/tools/generate.mjs:', stale.join(', '));
  process.exit(1);
}
